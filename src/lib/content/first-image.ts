/*
  본문에서 처음 나오는 그림 (ADR-0058).

  커버가 없는 글은 이 그림이 대표 이미지가 된다. 동기화가 DB 에 넣을 때 고르고,
  미리보기가 화면을 그릴 때도 같은 규칙으로 골라야 발행한 모습과 어긋나지 않는다(ADR-0061).
  그래서 동기화 안에 두지 않고 꺼내 둔다.
*/

/** 본문에서 처음 나오는 그림. 마크다운 이미지 문법만 본다 */
export function firstImageOf(body: string): string | undefined {
  return body.match(/!\[[^\]]*\]\(([^)\s]+)/)?.[1];
}
